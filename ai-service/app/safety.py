"""Мінімальна безпечна гілка без LLM.
УВАГА: тексти й номери потрібно погодити зі шкільним психологом перед показом дітям."""
import re
from typing import Optional

_SERIOUS = [
    r"не хочу жити", r"хочу померти", r"покінчити з собою", r"вбити себе",
    r"зробити собі боляче", r"завдати собі шкоди", r"мене б.?ють", r"мене б.?є",
]
_DISTRESS = [
    r"мені (дуже )?страшно", r"\bбоюс[ья]\b", r"не можу більше",
    r"мені (дуже )?погано", r"паніка", r"мені тривожно",
]

SERIOUS_TEXT = (
    "Мені дуже шкода, що тобі зараз так важко. Ти не сам і не винен. "
    "Скажи про це дорослому, якому довіряєш, просто зараз. "
    "Також можна подзвонити на Національну дитячу гарячу лінію 116 111. "
    "Якщо щось загрожує тобі просто зараз, дзвони 112."
)
DISTRESS_TEXT = (
    "Схоже, тобі зараз страшно або тривожно. Це нормально. "
    "Давай зробимо паузу: повільно вдихни на 4 рахунки й видихни на 6. "
    "Якщо поруч є дорослий, якому ти довіряєш, побудь біля нього. "
    "До навчання повернемось, коли будеш готовий."
)


def check_safety(message: str) -> Optional[str]:
    text = (message or "").lower()
    if any(re.search(p, text) for p in _SERIOUS):
        return SERIOUS_TEXT
    if any(re.search(p, text) for p in _DISTRESS):
        return DISTRESS_TEXT
    return None